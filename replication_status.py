"""Regenerate replication/STATUS.md: which conditions each replication model has scored, from the files on disk.

The models are configs/replication/*.yaml, without validate-*; each one's conditions are its config's (replication.py).
A cell is:
- done: outputs/replication/<key>/results/<stage>__<condition>.csv.gz exists, shown with its median outcome mass and
  split-half reliability (replication_analysis.cell_info, cached per file), flagged where it fails a gate (mass below 0.2:
  no call; split-half below 0.9);
- pilot: only the --pilot file (pilot/...);
- missing.
Below the grid: each model's last finished condition and scoring time (progress.jsonl), and the calls from its last
replication_analysis.py run (analysis/findings.csv), if any.

Usage: uv run python replication_status.py
"""

import json
import time
from pathlib import Path

import replication_analysis as ra
from replication import BASE_CONDITIONS, FINAL_CONDITIONS, expand_conditions

STATUS = Path("replication/STATUS.md")
STAGE_DEFAULT = {"base": BASE_CONDITIONS, "instruct": FINAL_CONDITIONS}


def configured():
    """[(key, config)] of the replication's models."""
    import yaml
    out = []
    for path in sorted(ra.CONFIGS.glob("*.yaml")):
        if path.stem.startswith("validate-"):
            continue
        cfg = yaml.safe_load(path.read_text()) or {}
        out.append((cfg.get("run_name", path.stem), cfg))
    return out


def planned(cfg):
    """["stage/condition"] the config asks for, base first."""
    keys = []
    for m in sorted(cfg.get("models", []), key=lambda m: m.get("stage") != "base"):
        spec = m.get("conditions", "base" if m.get("stage") == "base" else "final")
        keys += [f"{m['stage']}/{c}" for c in expand_conditions(spec)]
    return keys or [f"{s}/{c}" for s, cs in STAGE_DEFAULT.items() for c in cs]


def cell_text(model, key):
    if key in model.cells:
        info = model.cells[key]
        flags = [f for f, bad in (("low mass", info["median_mass"] < ra.MIN_MASS),
                                  ("split-half < 0.9", info["reliability"] < ra.MIN_RELIABILITY)) if bad]
        text = f"{info['median_mass']:.2f} / {info['reliability']:.3f}"
        return text + (f" **{', '.join(flags)}**" if flags else "")
    return "*pilot*" if key in model.pilots else "–"


def progress(model):
    path = model.dir / "progress.jsonl"
    if not path.exists():
        return "", 0.0
    lines = [json.loads(x) for x in path.read_text().splitlines() if x.strip()]
    full = [x for x in lines if not x.get("pilot")]
    hours = sum(x.get("seconds", 0) for x in full) / 3600
    last = full[-1] if full else None
    return (f"{last['stage']}/{last['condition']} at {last['time']}" if last else ""), hours


def render(models, now=None):
    now = now or time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime())
    L = ["# Replication status", "",
         f"Regenerated by `uv run python replication_status.py` from the files on disk, {now}. Each cell: median outcome "
         "mass / split-half reliability for a scored condition; *pilot* where only the 24-pair pilot exists; – where "
         "nothing is. Flagged: median mass below 0.2 (reported, no call) and split-half below 0.9.", ""]
    if not models:
        L.append("No replication models are configured yet (`configs/replication/*.yaml`, excluding `validate-*`).")
        return "\n".join(L) + "\n"
    L += ["| model | key | base done | final done | pilot only | last finished | scoring hours |",
          "|---|---|---|---|---|---|---|"]
    for key, (model, keys) in models.items():
        done = {s: sum(k in model.cells for k in keys if k.startswith(f"{s}/")) for s in ("base", "instruct")}
        total = {s: sum(k.startswith(f"{s}/") for k in keys) for s in ("base", "instruct")}
        pilot = sum(k in model.pilots and k not in model.cells for k in keys)
        last, hours = progress(model)
        L.append(f"| {model.label} | `{key}` | {done['base']}/{total['base']} | {done['instruct']}/{total['instruct']} | "
                 f"{pilot} | {last} | {hours:.1f} |")
    order = list(dict.fromkeys(k for _, keys in models.values() for k in keys))
    L += ["", "## Conditions", "", "| condition | " + " | ".join(m.label for m, _ in models.values()) + " |",
          "|---|" + "---|" * len(models)]
    for k in order:
        L.append(f"| `{k}` | " + " | ".join(cell_text(m, k) if k in keys else "n/a" for m, keys in models.values()) + " |")
    calls = {key: ra.read_findings(key) for key in models}
    if any(calls.values()):
        L += ["", "## Calls (from the last `replication_analysis.py` run)", "",
              "| finding | " + " | ".join(m.label for m, _ in models.values()) + " |", "|---|" + "---|" * len(models)]
        for f, p in ra.matrix_rows():
            name = f"{f}. {ra.FINDINGS[f]}" + (f", {p}" if p else "")
            cells = []
            for key in models:
                r = calls[key].get((f, p))
                cells.append(f"{r['call']} ({r['key_number']})" if r and r["key_number"] else r["call"] if r else "–")
            L.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(L) + "\n"


def main():
    models = {}
    for key, cfg in configured():
        model = ra.Model(key)
        if not ra.read_config(key):  # nothing scored yet and the config is under another name
            model.label = ra.model_label(key, cfg)
        models[key] = (model, planned(cfg))
    STATUS.parent.mkdir(parents=True, exist_ok=True)
    STATUS.write_text(render(models))
    print(f"wrote {STATUS} ({len(models)} models)")


if __name__ == "__main__":
    main()
